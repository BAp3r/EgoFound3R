def evenly_spaced_marker_vertex_ids(marker_count: int, *, vertex_count: int = MANO_VERTEX_COUNT) -> list[int]:
    if marker_count <= 0:
        raise ValueError("marker_count must be a positive integer")
    if marker_count > vertex_count:
        raise ValueError(f"marker_count={marker_count} exceeds MANO vertex_count={vertex_count}")
    if marker_count == vertex_count:
        return list(range(vertex_count))
    if marker_count == 1:
        return [vertex_count // 2]
    return [
        round(index * float(vertex_count - 1) / float(marker_count - 1))
        for index in range(marker_count)
    ]


def marker_vertex_ids_for_count(marker_count: int) -> list[int]:
    if marker_count == len(MANO_MESHGRAPHORMER_LEVEL1_MARKER_VERTEX_IDS_195):
        return list(MANO_MESHGRAPHORMER_LEVEL1_MARKER_VERTEX_IDS_195)
    if marker_count == len(MANO_SEMANTIC_GEODESIC_MARKER_VERTEX_IDS_128):
        return list(MANO_SEMANTIC_GEODESIC_MARKER_VERTEX_IDS_128)
    return evenly_spaced_marker_vertex_ids(marker_count)
