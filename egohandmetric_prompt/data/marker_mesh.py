def marker_faces_for_count(marker_count: int) -> torch.Tensor:
    if marker_count == len({index for face in MANO_MESHGRAPHORMER_LEVEL1_MARKER_FACES_195 for index in face}):
        return torch.tensor(MANO_MESHGRAPHORMER_LEVEL1_MARKER_FACES_195, dtype=torch.long)
    return torch.zeros((0, 3), dtype=torch.long)


def marker_face_incidence_degree(marker_faces: torch.Tensor, *, marker_count: int) -> torch.Tensor:
    marker_count = int(marker_count)
    if marker_count <= 0:
        raise ValueError("marker_count must be positive")
    if marker_faces.ndim != 2 or marker_faces.shape[-1] != 3:
        raise ValueError("marker_faces must have shape [F, 3]")
    if marker_faces.dtype != torch.long:
        raise ValueError("marker_faces must use torch.long indices")
    if marker_faces.numel() == 0:
        return torch.zeros(marker_count, dtype=torch.long, device=marker_faces.device)
    if int(marker_faces.min().item()) < 0 or int(marker_faces.max().item()) >= marker_count:
        raise ValueError("marker_faces contains an out-of-range marker index")
    degree = torch.bincount(marker_faces.reshape(-1), minlength=marker_count)
    if tuple(degree.shape) != (marker_count,):
        raise RuntimeError("marker face incidence degree has an invalid shape")
    if torch.any(degree == 0):
        raise ValueError("marker_faces must cover every marker vertex")
    return degree


def marker_edges_for_count(marker_count: int) -> torch.Tensor:
    faces = marker_faces_for_count(marker_count)
    if faces.numel() == 0:
        return torch.zeros((0, 2), dtype=torch.long)
    edge_set: set[tuple[int, int]] = set()
    for face in faces.tolist():
        for start, end in ((0, 1), (1, 2), (2, 0)):
            edge_set.add(tuple(sorted((int(face[start]), int(face[end])))))
    return torch.tensor(sorted(edge_set), dtype=torch.long)
